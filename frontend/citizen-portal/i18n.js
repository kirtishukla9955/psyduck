    let currentLang = 'en';
    let onLanguageChangeCallbacks = [];

    function initI18n() {
        const savedLang = localStorage.getItem('dharaa_citizen_lang') || 'en';
        setLanguage(savedLang, false);
    }

    function getLanguage() {
        return currentLang;
    }

    function getLanguageMeta(code) {
        return LANGUAGES[code] || LANGUAGES.en;
    }

    function getAllLanguages() {
        return Object.values(LANGUAGES);
    }

    function t(key, fallbackText = null) {
        const langDict = TRANSLATIONS[currentLang];
        if (langDict && langDict[key] !== undefined) {
            return langDict[key];
        }
        const fallbackDict = TRANSLATIONS.en;
        if (fallbackDict && fallbackDict[key] !== undefined) {
            return fallbackDict[key];
        }
        return fallbackText !== null ? fallbackText : key;
    }

    function applyTranslations() {
        // Translate textContent
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            const translation = t(key);
            if (translation) {
                const icon = el.querySelector('i, svg');
                if (icon) {
                    const iconClone = icon.cloneNode(true);
                    el.textContent = ' ';
                    el.prepend(iconClone);
                    el.appendChild(document.createTextNode(translation));
                } else {
                    el.textContent = translation;
                }
            }
        });

        // Translate placeholders
        document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            const key = el.getAttribute('data-i18n-placeholder');
            const translation = t(key);
            if (translation) el.setAttribute('placeholder', translation);
        });

        // Translate title / aria-label
        document.querySelectorAll('[data-i18n-title]').forEach(el => {
            const key = el.getAttribute('data-i18n-title');
            const translation = t(key);
            if (translation) {
                el.setAttribute('title', translation);
                el.setAttribute('aria-label', translation);
            }
        });
    }

    function setLanguage(langCode, triggerCallbacks = true) {
        if (!LANGUAGES[langCode]) {
            langCode = 'en';
        }
        currentLang = langCode;
        localStorage.setItem('dharaa_citizen_lang', langCode);

        const meta = LANGUAGES[langCode];
        document.documentElement.lang = meta.code;
        document.documentElement.dir = meta.dir;

        // Apply translations across DOM
        applyTranslations();

        // Update language selector dropdown label if present
        const currentLangDisplay = document.getElementById('langSelectorCurrentName');
        if (currentLangDisplay) {
            currentLangDisplay.textContent = `${meta.native} (${meta.name})`;
        }

        // Highlight active language in dropdown
        document.querySelectorAll('.lang-menu-item').forEach(item => {
            item.classList.toggle('active', item.getAttribute('data-lang') === langCode);
        });

        // Update profile pills if present
        document.querySelectorAll('.lang-pill').forEach(btn => {
            const btnLang = btn.getAttribute('data-lang') || btn.id.replace('langBtn', '').toLowerCase();
            btn.classList.toggle('active', btnLang === langCode);
        });

        if (triggerCallbacks) {
            onLanguageChangeCallbacks.forEach(cb => {
                try { cb(langCode, meta); } catch (e) { console.error('i18n callback error:', e); }
            });
        }
    }

    function onLanguageChange(callback) {
        if (typeof callback === 'function') {
            onLanguageChangeCallbacks.push(callback);
        }
    }

    window.DharaaI18n = {
        LANGUAGES,
        TRANSLATIONS,
        initI18n,
        getLanguage,
        getLanguageMeta,
        getAllLanguages,
        t,
        setLanguage,
        applyTranslations,
        onLanguageChange
    };

